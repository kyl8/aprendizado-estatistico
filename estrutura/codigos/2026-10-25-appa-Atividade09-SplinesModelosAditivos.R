source("estrutura/codigos/2026-09-15-appa-PrepararBaseSinistros.R")
set.seed(20261025)
amostra <- boletins[, c("veiculos", "qtd_gravidade_fatal")]; names(amostra) <- c("x", "y")
amostra <- amostra[is.finite(amostra$x) & is.finite(amostra$y), ]
if (nrow(amostra) > 12000) amostra <- amostra[sample(nrow(amostra), 12000), ]
set.seed(9); dobra <- sample(rep(1:5, length.out = nrow(amostra)))
rmse <- function(y, p) sqrt(mean((y - p)^2))
cv_modelo <- function(ajusta, preve) { p <- numeric(nrow(amostra)); for (j in 1:5) { tr <- amostra[dobra != j, ]; va <- amostra[dobra == j, ]; p[dobra == j] <- preve(ajusta(tr), va) }; list(rmse = rmse(amostra$y, p), previsto = p) }
reta <- cv_modelo(function(tr) lm(y ~ x, data = tr), function(m, va) predict(m, va))
polinomio <- cv_modelo(function(tr) lm(y ~ poly(x, 2), data = tr), function(m, va) predict(m, va))
dfs <- c(3, 5, 7)
splines_cv <- lapply(dfs, function(df) cv_modelo(function(tr) lm(y ~ splines::ns(x, df = df), data = tr), function(m, va) predict(m, va)))
if (!requireNamespace("mgcv", quietly = TRUE)) stop("O pacote mgcv nao esta disponivel.")
gam_cv <- cv_modelo(function(tr) mgcv::gam(y ~ s(x, k = 8), data = tr, method = "REML"), function(m, va) predict(m, va))
nomes_spline <- paste0("spline_natural_df", dfs)
metricas <- data.frame(modelo = c("reta", "polinomio_grau_2", nomes_spline, "gam"), rmse_cv5 = c(reta$rmse, polinomio$rmse, vapply(splines_cv, `[[`, numeric(1), "rmse"), gam_cv$rmse))
melhor_df <- dfs[which.min(metricas$rmse_cv5[match(nomes_spline, metricas$modelo)])]
modelo_spline <- lm(y ~ splines::ns(x, df = melhor_df), data = amostra)
modelo_gam <- mgcv::gam(y ~ s(x, k = 8), data = amostra, method = "REML")
g <- seq(min(amostra$x), max(amostra$x), length.out = 200)
dir.create("estrutura/resultados", showWarnings = FALSE, recursive = TRUE)
write.csv(metricas, "estrutura/resultados/2026-10-25-appa-09-MetricasSplines.csv", row.names = FALSE, fileEncoding = "UTF-8")
png("estrutura/resultados/2026-10-25-appa-09-SplinesGAM.png", width = 1200, height = 650, res = 120)
par(mfrow = c(1, 2))
plot(amostra$x, amostra$y, pch = 16, cex = .35, col = rgb(0, 0, 0, .12), xlab = "Veiculos envolvidos", ylab = "Vitimas fatais", main = "Spline natural")
lines(g, predict(modelo_spline, data.frame(x = g)), col = "#19647E", lwd = 3)
plot(amostra$x, amostra$y, pch = 16, cex = .35, col = rgb(0, 0, 0, .12), xlab = "Veiculos envolvidos", ylab = "Vitimas fatais", main = "Modelo aditivo")
lines(g, predict(modelo_gam, data.frame(x = g)), col = "#C45C26", lwd = 3); dev.off()
cat("Amostra:", nrow(amostra), "| melhor df:", melhor_df, "\n"); print(metricas)
