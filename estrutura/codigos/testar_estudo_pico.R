# Verifica limites do alvo, dados invalidos e metricas sem depender da base real.
source("estrutura/codigos/estudo_pico_funcoes.R", local=TRUE, encoding="UTF-8")
horas <- c("06:29","06:30","08:30","08:31","11:29","11:30","13:30","13:31","16:59","17:00","19:30","19:31")
stopifnot(identical(pico_horario(horas), rep(c(0L,1L,1L,0L),3)))
invalidos <- c(NA,"","24:00","12:60","-1:20","ab:30","06x30","06:30lixo","6:30")
stopifnot(all(is.na(minutos_horario(invalidos))), all(is.na(pico_horario(invalidos))))
y <- rep(c(0L,1L),50000)
stopifnot(auc_pico(y,y)==1, auc_pico(y,1-y)==0, auc_pico(y,rep(.5,length(y)))==.5)
stopifnot(is.na(auc_pico(c(1,1),c(.3,.4))))
m <- metricas_pico(c(0,1),c(0,1)); stopifnot(m['brier']==0, m['auc']==1, m['acuracia']==1)
stopifnot(inherits(try(metricas_pico(c(0,1),c(-.1,1.1)),silent=TRUE),'try-error'))
w <- wald_pico(c(a=2,b=0),diag(2)); stopifnot(w['estatistica']==4, w['gl']==2)
extremo <- wald_pico(100,matrix(1)); stopifnot(is.finite(extremo['log_p_valor']),extremo['log_p_valor']<0)
cat("Testes do estudo de pico: OK\n")
