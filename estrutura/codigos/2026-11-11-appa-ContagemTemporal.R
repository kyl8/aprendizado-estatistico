# Extensao da pergunta: contagem por hora do calendario, com zeros e teste futuro.
source("estrutura/codigos/2026-09-15-appa-PrepararBaseSinistros.R",local=TRUE,encoding="UTF-8")
source("estrutura/codigos/estudo_pico_funcoes.R",local=TRUE,encoding="UTF-8")
if (!requireNamespace("sandwich",quietly=TRUE)) stop("Instale sandwich.")
datas <- as.Date(boletins$data_sinistro,"%d/%m/%Y"); minutos <- minutos_horario(boletins$hora_sinistro)
ok <- !is.na(datas) & !is.na(minutos)
calendario <- seq(as.Date("2025-01-01"),as.Date("2026-06-30"),by="day")
stopifnot(all(datas[ok] %in% calendario))
eventos <- table(factor(datas[ok],levels=as.character(calendario)),factor(minutos[ok]%/%60,levels=0:23))
d <- as.data.frame(eventos); names(d)<-c("data","hora","n")
d$data <- as.Date(as.character(d$data)); d$hora <- factor(d$hora,levels=as.character(0:23))
d$dia <- factor(format(d$data,"%u"),levels=as.character(1:7))
stopifnot(nrow(d)==length(calendario)*24, sum(d$n)==sum(ok), !anyDuplicated(d[,c("data","hora")]), all(d$n>=0))
tr <- d[d$data<as.Date("2026-01-01"),]; te <- d[d$data>=as.Date("2026-01-01"),]
stopifnot(max(tr$data)<min(te$data))
m <- glm(n ~ hora+dia,data=tr,family=poisson())
quasi <- glm(n ~ hora+dia,data=tr,family=quasipoisson())
stopifnot(m$converged,quasi$converged,max(abs(coef(m)-coef(quasi)))<1e-7)
phi <- sum(residuals(m,type="pearson")^2)/df.residual(m)
prev <- data.frame(te,base=mean(tr$n),poisson=as.numeric(predict(m,te,type="response")))
stopifnot(all(is.finite(prev$poisson)),all(prev$poisson>0))
met <- data.frame(modelo=c("base","poisson"),rmse=c(sqrt(mean((te$n-prev$base)^2)),sqrt(mean((te$n-prev$poisson)^2))),mae=c(mean(abs(te$n-prev$base)),mean(abs(te$n-prev$poisson))))
cov <- sandwich::vcovCL(m,cluster=tr$data,type="HC1",cadjust=TRUE)
testes <- do.call(rbind,lapply(c("hora","dia"),function(v) {
 i<-grep(paste0("^",v),names(coef(m))); data.frame(variavel=v,t(wald_pico(coef(m)[i],cov[i,i,drop=FALSE])))
}))
testes$p_holm <- p.adjust(testes$p_valor,"holm")
cs <- coef(summary(quasi))
coefs <- data.frame(termo=names(coef(m)),beta=coef(m),razao_contagens=exp(coef(m)),ep_quasi=cs[,2],ep_dia=sqrt(diag(cov)),row.names=NULL)
coefs$ic95_dia_inferior<-exp(coefs$beta-1.96*coefs$ep_dia);coefs$ic95_dia_superior<-exp(coefs$beta+1.96*coefs$ep_dia)
ganho <- aggregate(cbind(ganho=(te$n-prev$base)^2-(te$n-prev$poisson)^2,n=rep(1,nrow(te))),list(data=te$data),sum)
ganho<-ganho[order(ganho$data),]; nd<-nrow(ganho);stopifnot(all(diff(ganho$data)==1),sum(ganho$n)==nrow(te))
set.seed(20261113)
boot <- replicate(1000,{inicio<-sample.int(nd,ceiling(nd/7),replace=TRUE);i<-as.vector(outer(0:6,inicio,function(a,b)(a+b-1)%%nd+1))[seq_len(nd)];sum(ganho$ganho[i])/sum(ganho$n[i])})
ic<-quantile(boot,c(.025,.975))
incerteza<-data.frame(contraste="MSE base - MSE poisson",estimativa=met$rmse[1]^2-met$rmse[2]^2,ic95_inferior=unname(ic[1]),ic95_superior=unname(ic[2]),bloco_dias=7,repeticoes=1000)
auditoria<-data.frame(eventos=sum(ok),dias=length(calendario),celulas=nrow(d),zeros=sum(d$n==0),n_treino=nrow(tr),n_teste=nrow(te),phi_pearson_treino=phi,unidade="uma hora de um dia de calendario")
out<-"estrutura/codigos/resultados/contagem-temporal";dir.create(out,recursive=TRUE,showWarnings=FALSE)
for(nome in c("prev","met","testes","coefs","incerteza","auditoria"))write.csv(get(nome),file.path(out,paste0(nome,".csv")),row.names=FALSE,fileEncoding="UTF-8")
medias<-aggregate(cbind(observado=prev$n,previsto=prev$poisson),list(hora=as.integer(as.character(prev$hora))),mean)
png(file.path(out,"perfil-horario-teste.png"),1000,650,res=120);matplot(medias$hora,medias[,2:3],type="l",lty=1:2,col=c("gray30","steelblue"),lwd=2,xlab="Hora",ylab="Sinistros medios por hora de calendario",main="Poisson: perfil horario no teste temporal");legend("topleft",c("Observado","Previsto"),lty=1:2,col=c("gray30","steelblue"),bty="n");dev.off()
print(auditoria);print(met);print(testes);print(incerteza)
